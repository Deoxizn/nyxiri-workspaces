#!/usr/bin/env bash
# One-time setup for Classic workspaces. Takes an optional ranges string
# (default "DP-1:1-5,HDMI-A-1:6-10", the same format as the card's
# Workspaces per monitor field; 0 means 10):
#   bash ~/.config/omarchy/plugins/devi.nyxiri-workspaces/scripts/setup-classic.sh
#   bash ~/.config/omarchy/plugins/devi.nyxiri-workspaces/scripts/setup-classic.sh "DP-1:1-5,HDMI-A-1:6-10"
# It does two things, both idempotent, and reloads Hyprland:
#   1. Appends the dofile block that loads this plugin's
#      hypr/classic-workspaces.lua to hyprland.lua (backing it up first).
#   2. Writes ~/.config/hypr/classic-workspaces-pinning.lua: one
#      hl.workspace_rule per workspace, binding it to its monitor, so
#      Super + 6 opens workspace 6 on HDMI-A-1 instead of the focused
#      monitor. The classic Lua only loads that file in classic mode, so
#      4.5's per-monitor blocks are untouched. Re-run with new ranges to
#      regenerate it; the card's ranges field is the display split, and
#      this file is the Hyprland split, so keep them the same.
# After this, the Classic toggle in the settings card switches modes on its
# own; nothing else needs editing. Run it with bash (pushes land mode 644).
set -euo pipefail

ranges="${1:-DP-1:1-5,HDMI-A-1:6-10}"
ranges="${ranges//[[:space:]]/}"

# Build the pinning file content from a ranges string like
# "DP-1:1-5,HDMI-A-1:6-10". Each entry becomes one hl.workspace_rule per
# workspace in it.
build_pinning() {
  local input="$1"
  local out="-- Generated by devi.nyxiri-workspaces scripts/setup-classic.sh from"
  out+=$'\n'"-- \"$input\". Re-run the script to regenerate."
  local entry name spec lo hi n
  local IFS=','
  for entry in $input; do
    name="${entry%%:*}"
    spec="${entry#*:}"
    [[ $name == "$entry" || -z $spec ]] && continue
    if [[ $spec == *-* ]]; then
      lo="${spec%%-*}"
      hi="${spec#*-}"
      [[ $lo == 0 ]] && lo=10
      [[ $hi == 0 ]] && hi=10
      [[ $lo =~ ^[0-9]+$ && $hi =~ ^[0-9]+$ ]] || continue
      for (( n = lo; n <= hi; n++ )); do
        out+=$'\n'"hl.workspace_rule({ workspace = \"$n\", monitor = \"$name\" })"
      done
    else
      [[ $spec == 0 ]] && spec=10
      [[ $spec =~ ^[0-9]+$ ]] || continue
      out+=$'\n'"hl.workspace_rule({ workspace = \"$spec\", monitor = \"$name\" })"
    fi
  done
  printf '%s\n' "$out"
}

conf="$HOME/.config/hypr/hyprland.lua"
marker="-- BEGIN devi.nyxiri-workspaces"
if grep -Fq -- "$marker" "$conf" 2>/dev/null; then
  echo "Classic workspaces block already in $conf; nothing to do."
else
  cp "$conf" "$conf.bak.$(date +%s)"
  cat >> "$conf" <<'LUA'
-- BEGIN devi.nyxiri-workspaces
do
  local path = os.getenv("HOME") .. "/.config/omarchy/plugins/devi.nyxiri-workspaces/hypr/classic-workspaces.lua"
  local file = io.open(path, "r")
  if file then file:close(); dofile(path) end
end
-- END devi.nyxiri-workspaces
LUA
  echo "Added Classic workspaces block to $conf (backup made)."
fi

pin="$HOME/.config/hypr/classic-workspaces-pinning.lua"
mkdir -p "$(dirname "$pin")"
build_pinning "$ranges" > "$pin"
echo "Wrote workspace pinning to $pin from \"$ranges\"."

hyprctl reload
hyprctl configerrors
echo "Done. Switch modes in the settings card, Workspaces tab, and set Workspaces per monitor to the same ranges."
